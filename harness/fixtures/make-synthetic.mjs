#!/usr/bin/env node
// Builds a synthetic run with known ground truth, so the analysis can be
// tested before the contracts are deployed and without spending gas.
//
// The point is not to fake a result. It is that the analysis makes a specific,
// falsifiable claim - that cross-chain legs carry clock offset while the
// end-to-end figure does not - and the only way to check that claim is to feed
// it data where the offset is a number we chose. Real testnet data cannot test
// this, because with real data the offset is exactly the thing nobody knows.
//
//   node harness/fixtures/make-synthetic.mjs

import { writeFileSync } from 'node:fs';

// Lasna's clock reads this many seconds behind Base Sepolia's. Negative means
// behind. The analysis is never told this number; it has to show up in the
// output on its own.
const LASNA_CLOCK_OFFSET_SEC = -5;

// Deterministic, so the fixture is stable and a diff means something changed.
const REACT_LATENCY_CYCLE = [1, 2, 2, 3];
const CALLBACK_LATENCY_CYCLE = [1, 2, 3, 2, 4];

const TRIGGERED = 120; // enough that p99 is reported
const UNTRIGGERED = 6;

const ORIGIN_BLOCK_0 = 9_000_000;
const ORIGIN_TS_0 = 1_765_000_000;
const PUSH_INTERVAL_SEC = 3;
const BLOCKS_PER_SEC = 5; // Base Sepolia, ~200ms blocks
const POLL_LAG_MS = 150;
const SEND_LEAD_MS = 400; // handed to cast this long before it was included

function makeSample(i, { triggered }) {
  const react = REACT_LATENCY_CYCLE[i % REACT_LATENCY_CYCLE.length];
  const callback = CALLBACK_LATENCY_CYCLE[i % CALLBACK_LATENCY_CYCLE.length];

  const originTs = ORIGIN_TS_0 + i * PUSH_INTERVAL_SEC;
  const originBlock = ORIGIN_BLOCK_0 + i * PUSH_INTERVAL_SEC * BLOCKS_PER_SEC;

  const reactionTs = originTs + react + LASNA_CLOCK_OFFSET_SEC;
  const executionTs = originTs + react + callback;
  const executionBlock = originBlock + (react + callback) * BLOCKS_PER_SEC;

  const sample = {
    index: i,
    seq: i + 1,
    pair: 'ETH/USD',
    price: triggered ? '1800000000000000000000' : '2200000000000000000000',
    triggered,
    origin: {
      chainId: 84532,
      txHash: '0x' + (i + 1).toString(16).padStart(64, '0'),
      blockNumber: originBlock,
      blockTimestamp: originTs,
      sentAtMs: originTs * 1000 - SEND_LEAD_MS,
    },
    reaction: {
      chainId: 5318007,
      blockNumber: 400_000 + i * 2,
      blockTimestamp: reactionTs,
      originBlock,
      observedAtMs: (originTs + react) * 1000 + POLL_LAG_MS,
    },
    execution: null,
  };

  if (triggered) {
    sample.execution = {
      chainId: 84532,
      blockNumber: executionBlock,
      blockTimestamp: executionTs,
      observedAtMs: executionTs * 1000 + POLL_LAG_MS,
    };
  }

  return { sample, endToEnd: triggered ? react + callback : null };
}

const samples = [];
const endToEndTrue = [];

for (let i = 0; i < TRIGGERED; i++) {
  const { sample, endToEnd } = makeSample(i, { triggered: true });
  samples.push(sample);
  endToEndTrue.push(endToEnd);
}

for (let i = 0; i < UNTRIGGERED; i++) {
  const { sample } = makeSample(TRIGGERED + i, { triggered: false });
  samples.push(sample);
}

// One sample whose reaction names a different origin block than the push
// landed in. It must be rejected, not averaged in: a mispaired sample is a
// latency between two unrelated events.
const mismatched = makeSample(TRIGGERED + UNTRIGGERED, { triggered: true }).sample;
mismatched.reaction.originBlock = mismatched.origin.blockNumber - 25;
samples.push(mismatched);

// Two that never got far enough to pair at all.
samples.push({ index: 900, failed: 'push', error: 'insufficient funds for gas' });
samples.push({
  index: 901,
  seq: 901,
  txHash: '0x' + 'ab'.repeat(32),
  failed: 'no-reaction',
  triggered: true,
});

const run = {
  startedAt: '2026-11-14T00:00:00.000Z',
  finishedAt: '2026-11-14T00:06:27.000Z',
  synthetic: true,
  options: { samples: samples.length, interval: 3000, poll: 250, timeout: 120000, pattern: 'alternate' },
  origin: {
    chainId: 84532,
    priceFeed: '0x0000000000000000000000000000000000000f33',
    executor: '0x0000000000000000000000000000000000000e73',
  },
  reactive: {
    chainId: 5318007,
    reactor: '0x0000000000000000000000000000000000000d33',
    floor: '2000000000000000000000',
  },
  notes: ['SYNTHETIC - generated by harness/fixtures/make-synthetic.mjs, not a real run.'],

  // Written down so the tests can check the analysis against numbers it was
  // never given.
  _groundTruth: {
    lasnaClockOffsetSec: LASNA_CLOCK_OFFSET_SEC,
    endToEndSecTrue: endToEndTrue,
    triggered: TRIGGERED,
    untriggered: UNTRIGGERED,
    mismatched: 1,
    collectionFailures: 2,
  },

  samples,
};

const out = new URL('./samples.synthetic.json', import.meta.url);
writeFileSync(out, JSON.stringify(run, null, 2) + '\n');
console.log(`wrote ${out.pathname} - ${samples.length} samples, offset ${LASNA_CLOCK_OFFSET_SEC}s`);
